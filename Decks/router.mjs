import { mountDeck, parseDeckHash } from './player.mjs';

const isDeckHash = hash => hash.startsWith('#/');
const deckMode = isDeckHash(window.location.hash);
const initialSlug = parseDeckHash(window.location.hash)?.slug;

// Crossing between the website and a deck gets a fresh document, so their
// animations, navigation and review tools never remain active together.
window.addEventListener('hashchange', () => {
  const nextDeckMode = isDeckHash(window.location.hash);
  const nextSlug = parseDeckHash(window.location.hash)?.slug;
  if (nextDeckMode === deckMode && (!deckMode || nextSlug === initialSlug)) return;
  document.documentElement.dataset.modeLoading = 'true';
  if (nextDeckMode) document.documentElement.dataset.deck = 'true';
  window.location.reload();
});

if (deckMode) {
  await mountDeck(window.location.hash);
  delete document.documentElement.dataset.modeLoading;
} else {
  const font = document.createElement('link');
  font.rel = 'preload';
  font.href = new URL('../assets/lovelo-black.woff2', import.meta.url).href;
  font.as = 'font';
  font.type = 'font/woff2';
  font.crossOrigin = 'anonymous';
  document.head.append(font);
  const websiteStyles = ['styles.css', 'art-direction.css', 'brand-proof.css', 'refinement.css', 'mobile-experience.css', 'motion.css', 'comments.css'];
  const styleLoads = await Promise.allSettled(websiteStyles.map(filename => new Promise((resolve, reject) => {
    const link = document.createElement('link');
    link.rel = 'stylesheet';
    link.href = new URL(`../${filename}`, import.meta.url).href;
    link.onload = resolve;
    link.onerror = () => reject(new Error(`Unable to load website stylesheet: ${filename}`));
    document.head.append(link);
  })));
  styleLoads.forEach(result => { if (result.status === 'rejected') console.error(result.reason); });
  if (document.fonts) await document.fonts.ready;
  delete document.documentElement.dataset.modeLoading;
  // These modules are copied or generated by the site build. Keep their URLs
  // dynamic so esbuild leaves the imports for the browser to resolve.
  const websiteScripts = ['../comments.js', '../app.js', '../mobile.js', '../js/motion.js'];
  await Promise.all(websiteScripts.map(script => {
    const moduleUrl = new URL(script, import.meta.url).href;
    return import(moduleUrl);
  }));
}
